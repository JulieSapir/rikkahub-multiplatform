// 版本号以 app/build.gradle.kts 的 defaultConfig 为准。:app 不在这个构建里，拿不到 AGP 的 android 扩展，
// 所以直接从脚本文本里读那两行；读不到就让构建失败，而不是悄悄沿用旧值
val appBuildScript = providers.fileContents(layout.projectDirectory.file("../app/build.gradle.kts")).asText

fun appDefaultConfig(key: String, pattern: String): Provider<String> = appBuildScript.map { text ->
    Regex("""\b$key\s*=\s*$pattern""").find(text)?.groupValues?.get(1)
        ?: error("app/build.gradle.kts 里找不到 $key，更新 linux/build.gradle.kts 的 appDefaultConfig")
}

val appVersionName = appDefaultConfig("versionName", "\"([^\"]+)\"")
val appVersionCode = appDefaultConfig("versionCode", "(\\d+)")

/** 生成桌面端的 BuildConfig，字段与上游 AGP 生成的一致（VERSION_NAME / VERSION_CODE 上游是 String 字段） */
abstract class GenerateBuildConfigTask : DefaultTask() {
    @get:Input
    abstract val versionName: Property<String>

    @get:Input
    abstract val versionCode: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val file = outputDir.get().asFile.resolve("me/rerere/rikkahub/BuildConfig.kt")
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by linux/build.gradle.kts from app/build.gradle.kts
            |package me.rerere.rikkahub
            |
            |object BuildConfig {
            |    const val APPLICATION_ID = "me.rerere.rikkahub"
            |    const val DEBUG = false
            |    const val VERSION_NAME = "${versionName.get()}"
            |    const val VERSION_CODE = "${versionCode.get()}"
            |    const val AUTHORITY = "me.rerere.rikkahub.fileprovider"
            |    // Play 渠道禁用自更新等入口的开关，桌面端不走 Play 商店，恒为 false
            |    const val IS_PLAY_STORE = false
            |}
            |
            """.trimMargin(),
            Charsets.UTF_8,
        )
    }
}

